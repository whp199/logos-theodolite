#!/usr/bin/env python3
# N1G_01_recorded_label_checks -- the label gate's check (backend/label_gate.py) for the labels the pages show from
# recordings, which carry too few words a side for the study's measure: the demonstration sighting (E6; 75 labelled
# faces, three words a side) and the vault's 24 recorded searches (E6_tool_audit_04_vault; 240 faces, five a side).
# Run (GPU, the whole card: stop the :8765 server first; it loads the model once):
#     .venv/bin/python -I experiments/scripts/N1G_01_recorded_label_checks.py
#   -> experiments/results/N1G_recorded_label_checks.json, its provenance sidecar
#      N1G_recorded_label_checks.provenance.json, and frontend/src/fixtures/recordedLabelChecks.ts (the pages read it)
# Without the model (CPU, no torch needed):
#     .venv/bin/python -I experiments/scripts/N1G_01_recorded_label_checks.py --empty
#   -> frontend/src/fixtures/recordedLabelChecks.ts only, with every face listed and every check null ("not yet
#      checked ten a side"); the pages then hold labels back by the layer alone.
#
# A label depends only on (layer, neuron, face): the face's write vector s * (W_down[:, n] (.) w_post), read through
# J++[layer] (the lens) and straight (the naked eye). No forward pass is needed. Each face is read by the server's own
# code, LarqlVaultEngine.inspect_bipolar_slot (DESCRIBE POLE; the same vector a sweep labels, theodolite_math.py
# extract_bipolar_poles), whose label_check counts the word-piece ids both readings share in their first ten, fp32 and
# softcapped, as N1 counted (N1C_02_matrix.py:248-255). The vault is fresh, so no edit is in force (edited false).
# Also recorded, as checks of the recording, not of the label:
#   - whether the first words each reading gives now are the words the recording shows (3 a side for the sighting,
#     5 for the vault), spelt exactly;
#   - for each recorded search, whether NEAREST run again lists the same neurons and faces in the same order, and
#     whether each NEAREST row's label_check equals DESCRIBE POLE's for that face.
# Layers count from 0 (page layer = layer + 1): the sighting's labelled layers are 5, 11, ..., 53 and 54-59; the vault's
# searches are at 20, 30, 40, 50, 55 and 58.
import argparse, hashlib, json, os, platform, subprocess, sys, time
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve()
REPO = HERE.parent.parent.parent
sys.path.insert(0, str(REPO))
RESULTS = REPO / "experiments" / "results"
OUT = RESULTS / "N1G_recorded_label_checks.json"
SIDECAR = RESULTS / "N1G_recorded_label_checks.provenance.json"
FIXTURE = REPO / "frontend" / "src" / "fixtures" / "e6-demo-sighting.json"
VAULT_REC = RESULTS / "E6_tool_audit_04_vault.partial.json"
MODULE = REPO / "frontend" / "src" / "fixtures" / "recordedLabelChecks.ts"


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def fixture_faces():
    """(key "layer:rank", layer, rank, neuron, face, recorded lens words, recorded eye words) for every labelled face of
    the demonstration sighting, in layer then rank order. The face is the sign of the recorded activation, as the
    pages take it (store/sighting.ts sightingFromFixture: a >= 0 is the positive face)."""
    f = json.loads(FIXTURE.read_text())
    out = []
    for key in sorted(f["poleLabels"]["lens"], key=lambda k: tuple(int(x) for x in k.split(":"))):
        l, r = (int(x) for x in key.split(":"))
        act = f["poleActs"][str(l)][r]
        out.append((key, l, r, int(f["poleNeurons"][str(l)][r]), 1 if act >= 0 else -1,
                    [t for t, _ in f["poleLabels"]["lens"][key]], [t for t, _ in f["poleLabels"]["eye"].get(key, [])]))
    return out


def vault_searches():
    """{"she@20": [(neuron, face, recorded lens words, recorded eye words), ...]} in the recording's order."""
    lists = json.loads(VAULT_REC.read_text())["lists"]
    return {k: [(int(r["n"]), 1 if r["pol"] >= 0 else -1, list(r["jv"]), list(r["nv"])) for r in v]
            for k, v in lists.items()}


def face_key(neuron: int, face: int) -> str:
    return f"{neuron}{'+' if face > 0 else '-'}"


def write_module(fixture_checks, vault_checks, run) -> None:
    """The small module the pages read: every recorded face, its server-shaped label_check or null."""
    lines = [
        "/**",
        " * GENERATED by experiments/scripts/N1G_01_recorded_label_checks.py: do not edit by hand.",
        " *",
        " * The label gate's check (backend/label_gate.py label_check, as the server sends it) for the labels the pages",
        " * show from recordings: the demonstration sighting's labelled faces (key \"layer:rank\", the fixture's own",
        " * poleLabels key) and the vault's recorded searches (key \"word@layer\", then \"neuron+\" or \"neuron-\" for the",
        " * face). Layers count from 0. A null check is a face not yet checked ten a side: the pages then hold its label",
        " * back by the layer alone. `RECORDED_LABEL_CHECKS_RUN` is null until the script has run on the GPU; then it",
        " * names the results file (experiments/results) and its sha256.",
        " */",
        'import type { RawLabelCheck } from "../lib/labels";',
        "",
        "export const RECORDED_LABEL_CHECKS_RUN: {",
        "  results: string;",
        "  sha256: string;",
        "  runAt: string;",
        "  lensId: string | null;",
        f"}} | null = {json.dumps(run, ensure_ascii=False)};",
        "",
        "export const FIXTURE_LABEL_CHECKS: Record<string, RawLabelCheck | null> = {",
    ]
    lines += [f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in fixture_checks.items()]
    lines += ["};", "", "export const VAULT_LABEL_CHECKS: Record<string, Record<string, RawLabelCheck | null>> = {"]
    for k, faces in vault_checks.items():
        lines.append(f"  {json.dumps(k)}: {{")
        lines += [f"    {json.dumps(fk)}: {json.dumps(v)}," for fk, v in faces.items()]
        lines.append("  },")
    lines += ["};", ""]
    MODULE.write_text("\n".join(lines))


def empty() -> int:
    fx = {key: None for key, *_ in fixture_faces()}
    vx = {k: {face_key(n, s): None for n, s, _, _ in rows} for k, rows in vault_searches().items()}
    write_module(fx, vx, None)
    print(f"wrote {MODULE.relative_to(REPO)}: {len(fx)} sighting faces and "
          f"{sum(len(v) for v in vx.values())} vault faces, every check null")
    return 0


def tokens(xs):
    return [t["token"] for t in xs]


def run_on_gpu() -> int:
    import torch
    from backend.engine_runtime import TheodoliteRuntime
    from backend.label_gate import LABEL_GATE_CARD
    from backend.larql_vault import LarqlVaultEngine

    t0 = time.time()
    rt = TheodoliteRuntime(load_jlens=False).load()
    vault = LarqlVaultEngine(rt)
    if vault.edits_in_force():
        raise SystemExit("a fresh vault has edits in force")
    lens = rt.lens_card()
    cache = {}

    def face(l: int, n: int, s: int):
        if (l, n) not in cache:
            cache[(l, n)] = vault.inspect_bipolar_slot(l, n, polarity=1.0)
        return cache[(l, n)]["north_pole" if s > 0 else "south_pole"]

    fixture = {}
    for key, l, r, n, s, rec_lens, rec_eye in fixture_faces():
        f = face(l, n, s)
        fixture[key] = {
            "layer": l, "rank": r, "neuron": n, "face": s, "label_check": f["label_check"],
            "lens_words": tokens(f["j_vindex_tokens"]), "eye_words": tokens(f["naive_tokens"]),
            "recorded_lens": rec_lens, "recorded_eye": rec_eye,
            "lens_words_as_recorded": tokens(f["j_vindex_tokens"])[: len(rec_lens)] == rec_lens,
            "eye_words_as_recorded": tokens(f["naive_tokens"])[: len(rec_eye)] == rec_eye,
        }
    torch.cuda.empty_cache()

    searches = {}
    for key, rows in vault_searches().items():
        word, layer = key.split("@")
        l = int(layer)
        again = vault.execute_lql(f"SELECT * FROM POLES NEAREST '{word}' WHERE layer = {l} LIMIT {len(rows)}")
        again_rows = again["results"]
        by_face = {face_key(x["neuron_idx"], 1 if x["polarity_num"] >= 0 else -1): x for x in again_rows}
        out_rows = []
        for n, s, rec_lens, rec_eye in rows:
            f = face(l, n, s)
            near = by_face.get(face_key(n, s))
            out_rows.append({
                "neuron": n, "face": s, "label_check": f["label_check"],
                "lens_words": tokens(f["j_vindex_tokens"]), "eye_words": tokens(f["naive_tokens"]),
                "lens_words_as_recorded": tokens(f["j_vindex_tokens"])[: len(rec_lens)] == rec_lens,
                "eye_words_as_recorded": tokens(f["naive_tokens"])[: len(rec_eye)] == rec_eye,
                "nearest_label_check_agrees": None if near is None else near["label_check"] == f["label_check"],
            })
        searches[key] = {
            "layer": l, "word": word,
            "rows_as_recorded": [(x["neuron_idx"], 1 if x["polarity_num"] >= 0 else -1) for x in again_rows]
            == [(n, s) for n, s, _, _ in rows],
            "rows": out_rows,
        }
        torch.cuda.empty_cache()

    def summary(checks):
        checks = list(checks)
        return {
            "faces": len(checks),
            "held_back": sum(c["held_back"] for c in checks),
            "below_layer_40": sum("below_layer_40" in c["reasons"] for c in checks),
            "shares_nothing": sum("shares_nothing" in c["reasons"] for c in checks),
            "shown": sum(not c["held_back"] for c in checks),
            "shown_by_shared_top10": {str(k): sum((not c["held_back"]) and c["shared_top10"] == k for c in checks)
                                      for k in range(11)},
        }

    vault_checks = [r["label_check"] for s in searches.values() for r in s["rows"]]
    out = {
        "what": ("The label gate's check for the labels the pages show from recordings: the demonstration sighting's "
                 "labelled faces and the vault's 24 recorded searches, each face read by the server's DESCRIBE POLE "
                 "(backend/larql_vault.py inspect_bipolar_slot). Layers count from 0 (page layer = layer + 1)."),
        "lens": lens,
        "label_gate": LABEL_GATE_CARD,
        "summary": {"fixture": summary(v["label_check"] for v in fixture.values()), "vault": summary(vault_checks),
                    "fixture_words_as_recorded": sum(v["lens_words_as_recorded"] and v["eye_words_as_recorded"]
                                                     for v in fixture.values()),
                    "vault_words_as_recorded": sum(r["lens_words_as_recorded"] and r["eye_words_as_recorded"]
                                                   for s in searches.values() for r in s["rows"]),
                    "vault_searches_as_recorded": sum(s["rows_as_recorded"] for s in searches.values()),
                    "vault_nearest_checks_agree": sum(bool(r["nearest_label_check_agrees"])
                                                      for s in searches.values() for r in s["rows"])},
        "fixture": {"source": "frontend/src/fixtures/e6-demo-sighting.json (poleNeurons, poleActs, poleLabels)",
                    "faces": fixture},
        "vault": {"source": "experiments/results/E6_tool_audit_04_vault.partial.json (lists)", "searches": searches},
    }
    OUT.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    run_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    head = subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    side = {
        "result": "experiments/results/N1G_recorded_label_checks.json",
        "result_sha256": sha256_of(OUT),
        "script": "experiments/scripts/N1G_01_recorded_label_checks.py",
        "script_sha256": sha256_of(HERE),
        "code_sha256": {p: sha256_of(REPO / p) for p in ("backend/label_gate.py", "backend/larql_vault.py",
                                                         "backend/theodolite_math.py", "backend/engine_runtime.py")},
        "inputs": [{"path": str(p.relative_to(REPO)), "sha256": sha256_of(p)} for p in (FIXTURE, VAULT_REC)],
        "model": rt.model_id,
        "lens": lens,
        "git_head_when_run": head,
        "run_at": run_at,
        "device": torch.cuda.get_device_name(0) if torch.cuda.is_available() else str(rt.device),
        "python": platform.python_version(), "torch": torch.__version__,
        "seconds": round(time.time() - t0, 1),
    }
    SIDECAR.write_text(json.dumps(side, indent=1, ensure_ascii=False) + "\n")
    write_module(
        {k: v["label_check"] for k, v in fixture.items()},
        {k: {face_key(r["neuron"], r["face"]): r["label_check"] for r in s["rows"]} for k, s in searches.items()},
        {"results": "experiments/results/N1G_recorded_label_checks.json", "sha256": side["result_sha256"],
         "runAt": run_at, "lensId": (lens or {}).get("id")},
    )
    print(json.dumps(out["summary"], indent=1))
    print("saved", OUT.name, SIDECAR.name, MODULE.name, f"{time.time() - t0:.0f}s")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--empty", action="store_true", help="write the pages' module with every check null (no model)")
    args = ap.parse_args()
    if args.empty:
        os.environ["CUDA_VISIBLE_DEVICES"] = ""
        return empty()
    return run_on_gpu()


if __name__ == "__main__":
    sys.exit(main())
